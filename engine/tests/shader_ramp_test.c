static void expect_sequence(int32_t current, int32_t target, int32_t step,
  const int32_t *expected, int count) {
  int i;

  for (i=0; i<count; i++) {
    current = ShaderStepToward(current, target, &step);
    assert(current == expected[i]);
  }
  assert(current == target);
  assert(step == 0);
}

